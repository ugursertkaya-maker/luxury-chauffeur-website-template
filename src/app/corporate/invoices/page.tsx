'use client'
import { useEffect, useState } from 'react'
import { useRouter } from 'next/navigation'
import CorporateSidebar from '@/components/CorporateSidebar'
import { brand } from '@/config/brand'

interface Invoice {
  id: string; invoice_number: string; period_start: string; period_end: string
  total_amount: number; status: string; sent_at: string | null; paid_at: string | null; created_at: string
}

function fmt(d: string) {
  return new Date(d.includes('T') ? d : d + 'T00:00:00').toLocaleDateString('en-US', { month: 'short', day: 'numeric', year: 'numeric' })
}

export default function CorporateInvoicesPage() {
  const router = useRouter()
  const [invoices, setInvoices] = useState<Invoice[]>([])
  const [account, setAccount] = useState<{ company_name: string; payment_terms: number } | null>(null)
  const [loading, setLoading] = useState(true)

  useEffect(() => {
    async function load() {
      const [ai, aa] = await Promise.all([
        fetch('/api/corporate/dashboard?type=invoices'),
        fetch('/api/corporate/dashboard?type=account'),
      ])
      if (ai.status === 401) { router.replace('/corporate/login'); return }
      const [di, da] = await Promise.all([ai.json(), aa.json()])
      setInvoices(di.invoices ?? [])
      setAccount(da.account ?? null)
      setLoading(false)
    }
    load()
  }, [router])

  async function logout() {
    await fetch('/api/corporate/auth', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ action: 'logout' }) })
    window.location.href = '/corporate/login'
  }

  const totalPaid = invoices.filter(i => i.status === 'paid').reduce((s, i) => s + Number(i.total_amount), 0)
  const totalUnpaid = invoices.filter(i => i.status === 'sent').reduce((s, i) => s + Number(i.total_amount), 0)

  if (loading) return (
    <div className="min-h-screen bg-[#0a1017] flex items-center justify-center">
      <div className="text-white text-sm">Loading…</div>
    </div>
  )

  return (
    <div className="min-h-screen bg-slate-50 flex">
      <CorporateSidebar company={account?.company_name} onLogout={logout} />
      <div className="flex-1 lg:ml-56">
        <div className="max-w-4xl mx-auto px-4 py-8 space-y-6">

          <h1 className="text-2xl font-bold text-slate-800">Invoices</h1>

          {/* Stats */}
          <div className="grid grid-cols-1 sm:grid-cols-3 gap-4">
            <div className="bg-white rounded-2xl p-5 border border-slate-100">
              <p className="text-xs text-white uppercase tracking-wide font-medium mb-1">Total Invoices</p>
              <p className="text-3xl font-bold text-slate-800">{invoices.length}</p>
            </div>
            <div className="bg-white rounded-2xl p-5 border border-slate-100">
              <p className="text-xs text-white uppercase tracking-wide font-medium mb-1">Outstanding</p>
              <p className="text-3xl font-bold text-amber-600">${totalUnpaid.toFixed(2)}</p>
              <p className="text-sm text-white mt-0.5">Net {account?.payment_terms ?? 30} days</p>
            </div>
            <div className="bg-white rounded-2xl p-5 border border-slate-100">
              <p className="text-xs text-white uppercase tracking-wide font-medium mb-1">Total Paid</p>
              <p className="text-3xl font-bold text-green-600">${totalPaid.toFixed(2)}</p>
            </div>
          </div>

          {invoices.length === 0 ? (
            <div className="bg-white rounded-2xl p-10 border border-slate-100 text-center text-white text-sm">
              No invoices yet. Invoices are generated by {brand.company.displayName} at the end of each billing period.
            </div>
          ) : (
            <div className="bg-white rounded-2xl border border-slate-100 overflow-hidden">
              <table className="w-full text-sm">
                <thead>
                  <tr className="border-b border-slate-100 text-xs text-white uppercase tracking-wide">
                    <th className="text-left px-5 py-3 font-medium">Invoice</th>
                    <th className="text-left px-5 py-3 font-medium hidden sm:table-cell">Period</th>
                    <th className="text-left px-5 py-3 font-medium hidden md:table-cell">Sent</th>
                    <th className="text-left px-5 py-3 font-medium">Status</th>
                    <th className="text-right px-5 py-3 font-medium">Amount</th>
                    <th className="px-3 py-3"></th>
                  </tr>
                </thead>
                <tbody className="divide-y divide-slate-50">
                  {invoices.map(inv => (
                    <tr key={inv.id} className="hover:bg-slate-50 transition-colors">
                      <td className="px-5 py-3.5 font-semibold text-slate-800">#{inv.invoice_number}</td>
                      <td className="px-5 py-3.5 text-white hidden sm:table-cell">
                        {fmt(inv.period_start)} – {fmt(inv.period_end)}
                      </td>
                      <td className="px-5 py-3.5 text-white hidden md:table-cell">
                        {inv.sent_at ? fmt(inv.sent_at) : '—'}
                      </td>
                      <td className="px-5 py-3.5">
                        <span className={`text-xs border rounded-full px-2.5 py-0.5 font-medium ${
                          inv.status === 'paid' ? 'bg-green-50 text-green-700 border-green-200' :
                          inv.status === 'sent' ? 'bg-yellow-50 text-yellow-700 border-yellow-200' :
                          'bg-slate-100 text-white border-slate-200'
                        }`}>
                          {inv.status === 'paid' ? `Paid ${inv.paid_at ? fmt(inv.paid_at) : ''}` : inv.status.charAt(0).toUpperCase() + inv.status.slice(1)}
                        </span>
                      </td>
                      <td className="px-5 py-3.5 text-right font-semibold text-slate-800">
                        ${Number(inv.total_amount).toFixed(2)}
                      </td>
                      <td className="px-3 py-3.5 text-right">
                        <a
                          href={`/api/corporate/invoice-pdf?invoice_id=${inv.id}`}
                          target="_blank"
                          rel="noopener noreferrer"
                          className="inline-flex items-center gap-1 text-xs font-medium text-white hover:text-slate-800 transition-colors"
                          title="Download PDF"
                        >
                          <svg className="w-4 h-4" fill="none" viewBox="0 0 24 24" stroke="currentColor" strokeWidth={1.8}>
                            <path strokeLinecap="round" strokeLinejoin="round" d="M12 10v6m0 0l-3-3m3 3l3-3M3 17V7a2 2 0 012-2h6l2 2h6a2 2 0 012 2v8a2 2 0 01-2 2H5a2 2 0 01-2-2z" />
                          </svg>
                          <span className="hidden sm:inline">PDF</span>
                        </a>
                      </td>
                    </tr>
                  ))}
                </tbody>
              </table>
            </div>
          )}

          <p className="text-xs text-white text-center">
            Questions about an invoice? Contact us at{' '}
            <a href={`mailto:${brand.contact.emailInfo}`} className="text-white hover:underline">{brand.contact.emailInfo}</a>
          </p>
        </div>
      </div>
    </div>
  )
}
